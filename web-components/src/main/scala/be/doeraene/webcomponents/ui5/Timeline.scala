/** The ui5-timeline component shows entries (such as objects, events, or posts) in chronological order. A common use
  * case is to provide information about changes to an object, or events related to an object. These entries can be
  * generated by the system (for example, value XY changed from A to B), or added manually. There are two distinct
  * variants of the timeline: basic and social. The basic timeline is read-only, while the social timeline offers a high
  * level of interaction and collaboration, and is integrated within SAP Jam.
  *
  * @see
  *   <a href="https://ui5.github.io/webcomponents/components/fiori/Timeline/">the doc</a> for more information.
  */
object Timeline extends WebComponent {

  @js.native
  trait RawElement extends js.Object {}

  @js.native
  @JSImport("@ui5/webcomponents-fiori/dist/Timeline.js", JSImport.Default)
  object RawImport extends js.Object

  // object-s are lazy so you need to actually use them in your code to prevent dead code elimination
  used(RawImport)

  type Ref = dom.html.Element & RawElement

  protected val tag: CustomHtmlTag[Ref] = CustomHtmlTag("ui5-timeline")

  lazy val accessibleName: HtmlAttr[String] = htmlAttr("accessible-name", StringAsIsCodec)

  lazy val layout: HtmlAttr[TimelineLayout]   = TimelineLayout.asHtmlAttr("layout")
  lazy val growing: HtmlAttr[TimelineGrowing] = TimelineGrowing.asHtmlAttr("growing")

  /** Whether to display a loading indicator over the Timeline. */
  lazy val loading: HtmlAttr[Boolean] = htmlAttr("loading", BooleanAsAttrPresenceCodec)

  /** Delay after which the loading indicator shows up (UI5 default: 1 second). */
  lazy val loadingDelay: HtmlAttr[FiniteDuration] = htmlAttr("loading-delay", FiniteDurationCodec)

  /** Whether the content of the `header` and `infoBar` slots remains visible when the user scrolls the Timeline (since
    * UI5 2.24).
    *
    * Note: the bars pin to the Timeline's own scroll container, so the Timeline needs a constrained height.
    */
  lazy val stickyHeader: HtmlAttr[Boolean] = htmlAttr("sticky-header", BooleanAsAttrPresenceCodec)

  object slots {

    /** Header of the Timeline, typically a [[Toolbar]] or a [[Bar]] (since UI5 2.24). */
    val header: Slot = Slot("header")

    /** Info bar displayed below the header, e.g. to show active filters (since UI5 2.24). */
    val infoBar: Slot = Slot("infoBar")
  }

  object events {

    /** Fired when the user presses the "More" button or scrolls to the end of the Timeline, when `growing` is set. */
    val onLoadMore: EventProp[EventWithPreciseTarget[Ref]] = new EventProp("load-more")
  }

  //noinspection TypeAnnotation
  def item  = TimelineItem
  def group = TimelineGroupItem

}
